// Озвучка русского произношения (Web Speech API)
window.speakPronounce = function(id, customText) {
  if (!('speechSynthesis' in window)) {
    alert('Голосовая озвучка не поддерживается вашим браузером.');
    return;
  }

  // Если уже говорит этот элемент — остановим
  if (window.speechSynthesis.speaking && currentSpeakingId === id) {
    window.speechSynthesis.cancel();
    currentSpeakingId = null;
    updateSpeakButtons();
    return;
  }

  window.speechSynthesis.cancel();

  let textToSpeak = customText;
  if (!textToSpeak) {
    const task = ALL_TASKS.find(t => t.id === id);
    if (task && task.pronounce) {
      textToSpeak = task.pronounce;
    }
  }

  if (!textToSpeak) return;

  const utterance = new SpeechSynthesisUtterance(textToSpeak);
  utterance.lang = "ru-RU";
  utterance.rate = 0.92; // Чёткий экзаменационный темп
  utterance.pitch = 1.0;

  const voices = window.speechSynthesis.getVoices();
  const ruVoice = voices.find(v => v.lang && (v.lang.startsWith("ru") || v.lang.includes("RU")));
  if (ruVoice) {
    utterance.voice = ruVoice;
  }

  currentSpeakingId = id;
  updateSpeakButtons();

  utterance.onend = () => {
    currentSpeakingId = null;
    updateSpeakButtons();
  };

  utterance.onerror = () => {
    currentSpeakingId = null;
    updateSpeakButtons();
  };

  window.speechSynthesis.speak(utterance);
};

function updateSpeakButtons() {
  document.querySelectorAll(".btn-speak").forEach(btn => {
    const btnId = btn.getAttribute("data-speak-id");
    if (btnId === currentSpeakingId) {
      btn.classList.add("speaking");
      btn.innerHTML = "⏹️ Стоп";
    } else {
      btn.classList.remove("speaking");
      btn.innerHTML = "🔊 Озвучить";
    }
  });
}

