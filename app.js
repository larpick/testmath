// Вспомогательная функция для рендеринга формул KaTeX
function renderKaTeX(el = document.body) {
  if (typeof window !== "undefined" && window.renderMathInElement) {
    try {
      window.renderMathInElement(el, {
        delimiters: [
          { left: "$$", right: "$$", display: true },
          { left: "$", right: "$", display: false },
          { left: "\\(", right: "\\)", display: false },
          { left: "\\[", right: "\\]", display: true }
        ],
        throwOnError: false
      });
    } catch (e) {
      console.warn("KaTeX render error:", e);
    }
  } else {
    setTimeout(() => renderKaTeX(el), 150);
  }
}

// Таймер обратного отсчета до комиссии: 13 октября 2026, 13:00 (МСК / местное время)
function updateCountdown() {
  const targetDate = new Date("2026-10-13T13:00:00");
  const now = new Date();
  const diff = targetDate - now;

  const timerEl = document.getElementById("countdownTimer");
  if (!timerEl) return;

  if (diff <= 0) {
    timerEl.textContent = "Экзамен начался!";
    timerEl.style.color = "#f43f5e";
    return;
  }

  const days = Math.floor(diff / (1000 * 60 * 60 * 24));
  const hours = Math.floor((diff / (1000 * 60 * 60)) % 24);
  const minutes = Math.floor((diff / (1000 * 60)) % 60);
  const seconds = Math.floor((diff / 1000) % 60);

  timerEl.textContent = `${days}д ${hours}ч ${minutes}м ${seconds}с`;
}

// Фильтрация задач
function getFilteredTasks() {
  let list = [];
  const learnedSet = getLearnedSet();

  switch (activeTab) {
    case "unlearned":
      list = ALL_TASKS.filter(t => !learnedSet.has(t.id));
      break;
    case "prob":
      list = [...EXAM_DATA.probTheory, ...EXAM_DATA.probPractice];
      break;
    case "math":
      list = [
        ...EXAM_DATA.mathMatrices,
        ...EXAM_DATA.mathDerivatives,
        ...EXAM_DATA.mathIntegrals,
        ...EXAM_DATA.mathLimits,
        ...EXAM_DATA.mathVectors
      ];
      break;
    case "math_matrices":
      list = EXAM_DATA.mathMatrices;
      break;
    case "math_derivatives":
      list = EXAM_DATA.mathDerivatives;
      break;
    case "math_integrals":
      list = EXAM_DATA.mathIntegrals;
      break;
    case "math_limits":
      list = EXAM_DATA.mathLimits;
      break;
    case "math_vectors":
      list = EXAM_DATA.mathVectors;
      break;
    case "all":
    default:
      list = ALL_TASKS;
      break;
  }

  if (searchQuery.trim()) {
    const q = searchQuery.toLowerCase().trim();
    list = list.filter(t =>
      t.title.toLowerCase().includes(q) ||
      t.problem.toLowerCase().includes(q) ||
      t.number.toLowerCase().includes(q) ||
      t.answer.toLowerCase().includes(q)
    );
  }

  return list;
}

// Обновление прогресс-бара
function updateProgress() {
  const learnedSet = getLearnedSet();
  const total = ALL_TASKS.length;
  const learnedCount = ALL_TASKS.filter(t => learnedSet.has(t.id)).length;
  const unlearnedCount = total - learnedCount;
  const percent = Math.round((learnedCount / total) * 100);

  const fillEl = document.getElementById("progressFill");
  const scoreEl = document.getElementById("progressScore");
  const statCountEl = document.getElementById("statCount");
  const statProbEl = document.getElementById("statProb");
  const statMathEl = document.getElementById("statMath");
  const tabUnlearnedCountEl = document.getElementById("tabUnlearnedCount");

  if (fillEl) fillEl.style.width = `${percent}%`;
  if (scoreEl) scoreEl.textContent = `${percent}% готово`;
  if (statCountEl) statCountEl.textContent = `${learnedCount} из ${total}`;
  if (tabUnlearnedCountEl) tabUnlearnedCountEl.textContent = unlearnedCount;

  const probTotal = EXAM_DATA.probTheory.length + EXAM_DATA.probPractice.length;
  const probLearned = [...EXAM_DATA.probTheory, ...EXAM_DATA.probPractice].filter(t => learnedSet.has(t.id)).length;
  if (statProbEl) statProbEl.textContent = `${probLearned}/${probTotal}`;

  const mathTotal = total - probTotal;
  const mathLearned = learnedCount - probLearned;
  if (statMathEl) statMathEl.textContent = `${mathLearned}/${mathTotal}`;

  document.querySelectorAll(".tab-btn").forEach(btn => {
    const tabKey = btn.getAttribute("data-tab");
    let countEl = btn.querySelector(".tab-count");
    if (!countEl) return;

    if (tabKey === "all") {
      countEl.textContent = `${learnedCount}/${total}`;
    } else if (tabKey === "unlearned") {
      countEl.textContent = unlearnedCount;
    } else if (tabKey === "prob") {
      countEl.textContent = `${probLearned}/${probTotal}`;
    } else if (tabKey === "math") {
      countEl.textContent = `${mathLearned}/${mathTotal}`;
    }
  });
}

